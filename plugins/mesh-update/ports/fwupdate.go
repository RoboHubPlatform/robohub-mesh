// The fwupdate port: what an update over the link needs that the Rho runtime
// does not have (MESH-0039, MESH-0040, robohub ADR-0022).
//
//   - fwupdate_keygen makes a mesh's Ed25519 update key: "<seed hex>|<public hex>";
//   - fwupdate_public is the public half of a seed;
//   - fwupdate_offer writes UPDATE_OFFER's payload for an image (robohub-protocol
//     PROTO-0008) — the manifest and its signature over "rh-update1" and the
//     manifest's bytes — as hex;
//   - fwupdate_header is the C header a build compiles the public key from
//     (robohub_update_key.h).
//
// Every argument and answer is a string; a bad argument is answered with "".
// The port holds no state, touches no file and logs nothing, so a key never
// leaves the call it was given to.
//
// A project of the robohub platform asks for it by name (`ports: [fwupdate]`).
package main

import (
	"crypto/ed25519"
	"crypto/rand"
	"crypto/sha256"
	"encoding/binary"
	"encoding/hex"
	"strconv"
	"strings"
)

const fwupdateDomain = "rh-update1"

func fwupdateSeed(seedHex string) ed25519.PrivateKey {
	seed, err := hex.DecodeString(strings.TrimSpace(seedHex))
	if err != nil || len(seed) != ed25519.SeedSize {
		return nil
	}
	return ed25519.NewKeyFromSeed(seed)
}

// fwupdateKeygen makes a key: its seed and its public half, as hex.
func fwupdateKeygen() string {
	public, private, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		return ""
	}
	return hex.EncodeToString(private.Seed()) + "|" + hex.EncodeToString(public)
}

// fwupdatePublic is a seed's public half, as hex.
func fwupdatePublic(seedHex string) string {
	key := fwupdateSeed(seedHex)
	if key == nil {
		return ""
	}
	return hex.EncodeToString(key.Public().(ed25519.PublicKey))
}

func fwupdateU32(text string) (uint32, bool) {
	n, err := strconv.ParseUint(strings.TrimSpace(text), 10, 32)
	return uint32(n), err == nil
}

// fwupdateOffer is UPDATE_OFFER's payload for an image, as hex:
//
//	1 | manifest | signature
//	manifest = 1 | update_id u32 | uid[8] | firmware u16 | security u32 | size u32 |
//	           sha256[32] | chunk_size u16
//	signature = Ed25519(seed, "rh-update1" | manifest)
func fwupdateOffer(seedHex, updateID, uidHex, firmware, security, chunk, image string) string {
	key := fwupdateSeed(seedHex)
	uid, err := hex.DecodeString(strings.TrimSpace(uidHex))
	id, okID := fwupdateU32(updateID)
	fw, okFW := fwupdateU32(firmware)
	sec, okSec := fwupdateU32(security)
	size, okChunk := fwupdateU32(chunk)
	if key == nil || err != nil || len(uid) != 8 || !okID || !okFW || fw > 0xFFFF || !okSec ||
		!okChunk || size == 0 || size > 0xFFFF || len(image) == 0 || uint64(len(image)) > 0xFFFFFFFF {
		return ""
	}
	digest := sha256.Sum256([]byte(image))
	manifest := make([]byte, 0, 57)
	manifest = append(manifest, 1)
	manifest = binary.LittleEndian.AppendUint32(manifest, id)
	manifest = append(manifest, uid...)
	manifest = binary.LittleEndian.AppendUint16(manifest, uint16(fw))
	manifest = binary.LittleEndian.AppendUint32(manifest, sec)
	manifest = binary.LittleEndian.AppendUint32(manifest, uint32(len(image)))
	manifest = append(manifest, digest[:]...)
	manifest = binary.LittleEndian.AppendUint16(manifest, uint16(size))
	signature := ed25519.Sign(key, append([]byte(fwupdateDomain), manifest...))
	offer := append([]byte{1}, manifest...)
	offer = append(offer, signature...)
	return hex.EncodeToString(offer)
}

// fwupdateHeader is robohub_update_key.h for a public key.
func fwupdateHeader(publicHex string) string {
	public, err := hex.DecodeString(strings.TrimSpace(publicHex))
	if err != nil || len(public) != ed25519.PublicKeySize {
		return ""
	}
	parts := make([]string, len(public))
	for i, b := range public {
		parts[i] = "0x" + hex.EncodeToString([]byte{b})
	}
	return "/* Generated by Mesh: this mesh's update public key (robohub ADR-0022). Not secret. */\n" +
		"#pragma once\n#define RH_UPDATE_KEY_PROVISIONED 1\n" +
		"static const unsigned char RH_UPDATE_PUBLIC_KEY[32] = { " + strings.Join(parts, ", ") + " };\n"
}
